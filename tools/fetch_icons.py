"""Fetches Material Symbols Rounded (Apache-2.0) SVGs and converts them to Android
VectorDrawables in app/src/main/res/drawable/ as ms_<name>.xml (outline) and
ms_<name>_fill.xml (FILL=1). Re-run after adding names to ICONS.

    python tools/fetch_icons.py
"""
import os
import re
import sys
import urllib.request

ICONS = """
add album apps arrow_back arrow_drop_down arrow_drop_up arrow_forward arrow_left arrow_right
block bluetooth bolt check check_circle chevron_right close cloud_sync cloud_upload
code contrast create_new_folder credit_card dark_mode delete description download draft edit
error explore extension fast_forward favorite folder folder_open folder_zip gamepad grid_view
history image info light_mode lock logout mail menu_book more_horiz more_vert open_in_new palette
pause play_arrow policy refresh settings_backup_restore rocket_launch save screenshot search search_off settings
shield smart_display speed sports_esports sports_motorsports star storefront swap_horiz tune
upload_file verified visibility volume_up warning workspace_premium bug_report graphic_eq
videogame_asset touch_app vibration star_rate sd_card schedule timer hd memory devices
keyboard_arrow_down keyboard_arrow_up library_books collections_bookmark
""".split()

FILLED = {"play_arrow", "star", "favorite", "check_circle", "bolt", "workspace_premium",
          "info", "error", "warning", "verified", "pause", "sports_esports", "settings",
          "explore", "collections_bookmark", "library_books", "grid_view"}

BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{f}.svg"
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")


def fetch(name, fill):
    f = f"{name}_fill1_24px" if fill else f"{name}_24px"
    with urllib.request.urlopen(BASE.format(n=name, f=f), timeout=30) as r:
        return r.read().decode()


def to_vector(svg):
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1).split()
    minx, miny, w, h = (float(v) for v in vb)
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths:
        raise ValueError("no path")
    body = "\n".join(
        f'        <path android:fillColor="@android:color/white" android:pathData="{d}" />' for d in paths
    )
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded (Apache-2.0), generated by tools/fetch_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{w:g}"
    android:viewportHeight="{h:g}"
    android:autoMirrored="false">
    <group android:translateX="{-minx:g}" android:translateY="{-miny:g}">
{body}
    </group>
</vector>
'''


def main():
    os.makedirs(OUT, exist_ok=True)
    failed = []
    for name in ICONS:
        for fill in (False, True) if name in FILLED else (False,):
            target = os.path.join(OUT, f"ms_{name}{'_fill' if fill else ''}.xml")
            try:
                xml = to_vector(fetch(name, fill))
            except Exception as e:  # noqa: BLE001
                failed.append(f"{name}{' fill' if fill else ''}: {e}")
                continue
            with open(target, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(xml)
    print(f"wrote icons to {os.path.abspath(OUT)}")
    if failed:
        print("FAILED:", *failed, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
